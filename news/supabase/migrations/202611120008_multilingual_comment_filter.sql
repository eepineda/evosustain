-- Diccionario multilingüe y configurable de términos y expresiones no permitidas.
-- La lista puede ampliarse con expresiones de cualquier idioma.
create table if not exists public.comment_blocklist (
  id bigint generated by default as identity primary key,
  term text not null unique,
  language_code text not null default 'und',
  category text not null check (category in ('profanity','slur','threat','spam','reserved_topic')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.comment_blocklist enable row level security;

